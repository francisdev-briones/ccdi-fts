<?php
require __DIR__ . '/config/bootstrap.php';
$u = require_login();

$p = one('SELECT p.*, s.name, s.category FROM payments p JOIN students s ON s.id=p.student_id WHERE p.id=? AND p.receipt_no IS NOT NULL', [(int)($_GET['id'] ?? 0)]);
// Students may open only their own receipts; cashier and dean may open any.
$allowed = $p && ($u['role'] === 'student' ? $p['student_id'] === $u['sid'] : in_array($u['role'], ['cashier', 'dean'], true));
if (!$allowed) { flash('Receipt not found.', 'err'); back(); }

$s = student($p['student_id']);
$payable = payable($s);
$paid = paid_sum($s['id']);

head_html('Acknowledgment ' . $p['receipt_no'], 'receipt-page');
nav_html();
echo '<main id="main" class="page narrow"><article class="receipt"><header><h2>Payment acknowledgment</h2><p class="rno">' . e($p['receipt_no']) . '</p></header>'
   . '<dl class="kv wide">'
   . '<dt>Received from</dt><dd>' . e($p['name']) . ' (' . e($p['student_id']) . ')</dd>'
   . '<dt>Amount</dt><dd class="big">' . e(peso($p['amount'])) . '</dd>'
   . '<dt>Method</dt><dd>' . e($p['method']) . '</dd>'
   . '<dt>Transaction reference</dt><dd>' . e($p['ref']) . '</dd>'
   . '<dt>Approved on</dt><dd>' . e($p['verified_at'] ? date('F j, Y g:i A', strtotime($p['verified_at'])) : '') . '</dd>'
   . '<dt>Total approved payments</dt><dd>' . e(peso($paid)) . ($payable !== null ? ' of ' . e(peso($payable)) : '') . '</dd>'
   . '</dl><p class="hint">This acknowledgment was generated by the CCDI Legazpi Student Financial Transaction System after staff approval.</p>'
   . '<div class="actions"><button class="btn" onclick="window.print()">Print acknowledgment</button> <a class="btn ghost" href="dashboard.php">Back to dashboard</a></div>'
   . '</article></main>';
foot_html();
